def validate_branch_effect_coverage(command_ids):
    actual = set(command_ids)
    expected = set(BRANCH_EFFECTS)
    if actual != expected:
        raise ValueError(f"Branch effect coverage differs: missing={sorted(actual - expected)}, stale={sorted(expected - actual)}")


def branch_effect(command_id):
    # Custom catalogues remain conservative; the shipped registry requires exact coverage.
    return BRANCH_EFFECTS.get(command_id, BranchEffect.PROTECTED)
